//render videos on the search page
function renderVideos(videos)
{
    videos.forEach(({thumbnail, link, title, author, stats})=>{
        const resultsContent = document.querySelector("div.results__content");
        const videoElement = 
        `
        <article class="results__video video">
            <div class="video__container">
                <a target="_blank" href="${link}" class="video__thumbnail">
                    <img src="${thumbnail}" alt="${author} - &quot;${title}&quot;">
                </a>
                <div class="video__body">
                    <h2 class="video__title">${title}</h2>
                    <p class="video__author"><span>By: </span> <em>${author}</em></p>
                    <div class="video__stats">
                        <div class="video__like-ratio">
                            <div class="video__like-measure">
                                <img src="./assets/images/thumb-up.svg" alt="Thumbs up">
                                ${stats.likes.toLocaleString()}
                            </div>
                            <div class="video__like-measure">
                                <img src="./assets/images/thumb-down.svg" alt="Thumbs down">
                                ${stats.dislikes.toLocaleString()}
                            </div>
                        </div>
                        <span> | </span>
                        <span class="video__views">${stats.watches.toLocaleString()} watched</span>
                    </div>
                </div>
            </div>
        </article>
        `;
        resultsContent.insertAdjacentHTML("beforeend", videoElement);
    })
}


//implementation
const { pathname } = location;
